#!/usr/bin/env node
// Draws the pixel-art backdrops used by themes, one pixel at a time.
//   public/img/sakura.svg   rising sun, hills, Mt. Fuji, a torii gate and a cherry tree
// Run with: npm run art
const fs = require('fs');
const path = require('path');

const W = 120, H = 26;

function canvas() {
  const px = Array.from({ length: H }, () => new Array(W).fill(null));
  const set = (x, y, c) => { if (x >= 0 && x < W && y >= 0 && y < H) px[y][Math.round(x)] = c; };
  const rect = (x, y, w, h, c) => { for (let j = y; j < y + h; j++) for (let i = x; i < x + w; i++) set(i, j, c); };
  const disc = (cx, cy, r, color) => {
    for (let y = Math.floor(cy - r); y <= cy + r; y++) {
      for (let x = Math.floor(cx - r); x <= cx + r; x++) {
        const d = (x - cx) ** 2 + (y - cy) ** 2;
        if (d <= r * r) set(x, y, typeof color === 'function' ? color(x, y, d) : color);
      }
    }
  };
  return { px, set, rect, disc };
}

// merge runs of the same color on each row into one rect
function toSvg(px, comment) {
  let rects = '';
  px.forEach((row, y) => {
    let x = 0;
    while (x < W) {
      const c = row[x];
      if (!c) { x++; continue; }
      let w = 1;
      while (row[x + w] === c) w++;
      rects += `<rect x="${x}" y="${y}" width="${w}" height="1" fill="${c}"/>`;
      x += w;
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMax slice" shape-rendering="crispEdges">\n<!-- ${comment} -->\n${rects}\n</svg>\n`;
}

function sakura() {
  const { px, set, rect, disc } = canvas();
  const C = {
    sun: '#F3A1B8', sunHi: '#F7BCCD',
    hill: '#F3DCE4', hillDk: '#EDCFDA',
    fuji: '#D9C6E6', fujiDk: '#C9B3DA', snow: '#FFFFFF', snowDk: '#EEE6F4',
    beam: '#3A2329', red: '#D9483B', redDk: '#B5382E',
    trunk: '#6B4A3A', bloom: '#F4A7C0', bloomHi: '#F9CADA', bloomDk: '#E98AAB',
  };

  // rising sun, lighter on the upper left
  disc(99, 6, 4.2, (x, y) => (x + y < 103 ? C.sunHi : C.sun));

  // Mt. Fuji: flat-topped cone, shaded on the right, jagged snow cap
  const peakX = 84, topY = 5;
  for (let y = topY; y < H; y++) {
    const hw = 2 + (y - topY) * 1.15;
    for (let x = Math.ceil(peakX - hw); x <= Math.floor(peakX + hw); x++) {
      const right = x > peakX + hw * 0.3;
      const snowLine = 10 + (x % 3 === 0 ? 1 : 0) + (x % 5 === 0 ? 1 : 0);
      if (y < snowLine) set(x, y, right ? C.snowDk : C.snow);
      else set(x, y, right ? C.fujiDk : C.fuji);
    }
  }

  // rolling hills in front of the mountain
  for (let x = 0; x < W; x++) {
    const h = Math.round(21.5 + 1.4 * Math.sin(x / 9) + 0.8 * Math.sin(x / 3.7));
    for (let y = h; y < H; y++) set(x, y, y === h ? C.hillDk : C.hill);
  }

  // torii gate: curved top beam, red lintel, tie beam, two pillars, name plaque
  rect(17, 8, 24, 1, C.beam); set(16, 7, C.beam); set(41, 7, C.beam);
  rect(18, 9, 22, 1, C.red);
  rect(21, 13, 16, 1, C.red);
  for (const x of [23, 33]) { rect(x, 9, 2, H - 9, C.red); rect(x + 1, 9, 1, H - 9, C.redDk); }
  rect(28, 10, 2, 3, C.beam);

  // cherry tree: trunk, two branches, dithered blossoms
  rect(5, 11, 2, H - 11, C.trunk);
  rect(7, 13, 4, 1, C.trunk); rect(2, 14, 3, 1, C.trunk);
  const bloom = (x, y, d) => ((x * 7 + y * 3) % 5 === 0 ? C.bloomHi : d > 6 && (x + y) % 4 === 0 ? C.bloomDk : C.bloom);
  disc(6, 8, 4.3, bloom); disc(11, 9.5, 3.4, bloom); disc(1.5, 10.5, 3, bloom); disc(12.5, 12.5, 2.2, bloom);

  return toSvg(px, 'Sakura theme backdrop, generated by scripts/build-theme-art.js');
}

const out = path.join(__dirname, '..', 'public', 'img');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'sakura.svg'), sakura());
console.log('Wrote public/img/sakura.svg');
